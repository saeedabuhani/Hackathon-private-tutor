export const t = translations;

export const SITE_LANGUAGES = ["en", "he", "ar"];
const LOCALES = { en: "en-US", he: "he-IL", ar: "ar" };

// Use in any client component:  const { t, dir } = useTranslation();  ...  <button>{t.testMe}</button>
export function useTranslation() {
  const siteLanguage = useStore((s) => s.siteLanguage);
  const lang = translations[siteLanguage] ? siteLanguage : "en";
  return {
    t: translations[lang],
    lang,
    dir: lang === "he" || lang === "ar" ? "rtl" : "ltr",
    locale: LOCALES[lang],
  };
}
