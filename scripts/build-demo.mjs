// Builds the static demo (no server, no keys) into ./demo-dist.
//
//   node scripts/build-demo.mjs
//
// It works on a temporary copy of the project: the API routes are removed (the demo answers /api/*
// in the browser from lib/demo/fixtures.js) and Next.js is switched to `output: "export"`.
import { cpSync, rmSync, mkdirSync, writeFileSync, readFileSync, existsSync, symlinkSync, readdirSync, statSync } from "node:fs";
import { join, resolve } from "node:path";
import { tmpdir } from "node:os";
import { spawnSync } from "node:child_process";

const root = resolve(import.meta.dirname, "..");
const work = join(tmpdir(), "leviathan-demo-build");
const skip = new Set(["node_modules", ".next", ".git", "demo-dist", "out", ".env.local", ".env"]);

rmSync(work, { recursive: true, force: true });
mkdirSync(work, { recursive: true });
for (const name of readdirSync(root)) {
  if (skip.has(name)) continue;
  cpSync(join(root, name), join(work, name), { recursive: true });
}
symlinkSync(join(root, "node_modules"), join(work, "node_modules"), "junction");

// the server side does not exist in the demo
rmSync(join(work, "app", "api"), { recursive: true, force: true });
rmSync(join(work, "app", "preview-ui"), { recursive: true, force: true });

writeFileSync(
  join(work, "next.config.mjs"),
  `/** Generated by scripts/build-demo.mjs */
export default { output: "export", trailingSlash: true, images: { unoptimized: true } };
`,
);

// dynamic routes need their ids listed for a static export
const dyn = join(work, "app", "(main)", "tutor", "[materialId]");
writeFileSync(
  join(dyn, "layout.js"),
  `export function generateStaticParams() {
  return [{ materialId: "m-js" }, { materialId: "m-react" }, { materialId: "m-db" }];
}
export const dynamicParams = false;
export default function Layout({ children }) {
  return children;
}
`,
);

const env = { ...process.env, NEXT_PUBLIC_DEMO: "true", NEXT_TELEMETRY_DISABLED: "1" };
const build = spawnSync(process.execPath, [join(root, "node_modules", "next", "dist", "bin", "next"), "build"], {
  cwd: work,
  env,
  stdio: "inherit",
});
if (build.status !== 0) process.exit(build.status || 1);

const out = join(root, "demo-dist");
rmSync(out, { recursive: true, force: true });
cpSync(join(work, "out"), out, { recursive: true });
// Netlify's free hosting injects an HTML comment right after <meta charset> in <head>. React treats a
// comment at the START of <head> as a hydration mismatch (error #418), so the charset meta is moved to
// the end of <head>, where the injected comment is harmless. The HTTP header already declares UTF-8.
const walk = (dir) =>
  readdirSync(dir).flatMap((n) => {
    const f = join(dir, n);
    return statSync(f).isDirectory() ? walk(f) : f.endsWith(".html") ? [f] : [];
  });
for (const file of walk(out)) {
  const meta = '<meta charSet="utf-8"/>';
  const html = readFileSync(file, "utf8");
  if (html.includes(meta)) writeFileSync(file, html.replace(meta, "").replace("</head>", meta + "</head>"));
}

if (!existsSync(join(out, "index.html"))) throw new Error("export produced no index.html");
console.log("Demo written to", out);
